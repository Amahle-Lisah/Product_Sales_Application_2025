    // Called by the Load button AND the Load menu item.
// Builds the report text, shows it in the text area,
// and shows the number of years processed in the label.
private void loadProductData() {
    StringBuilder report = new StringBuilder();

    report.append("Total Sales: ").append(sales.GetTotalSales()).append("\n");
    report.append(String.format("Average Sales: %.0f", sales.GetAverageSales())).append("\n");
    report.append("Sales over limit: ").append(sales.GetSalesOverLimit()).append("\n");
    report.append("Sales under limit: ").append(sales.GetSalesUnderLimit()).append("\n");

    txtAreaOutput.setText(report.toString());
    lblYearsProcessed.setText("Years Processed: " + sales.GetProductsProcessed());
}

// Called by the Save button AND the Save menu item.
// Writes the text area's contents to a file named data.txt.
private void saveProductData() {
    // There is nothing to save if the report has not been loaded yet
    if (txtAreaOutput.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Load the data first.");
        return;
    }

    // try-with-resources closes the file automatically when done
    try (PrintWriter out = new PrintWriter(new FileWriter("data.txt"))) {
        out.println("DATA LOG");
        out.println("**********************************");
        out.print(txtAreaOutput.getText());
        out.println("**********************************");
        JOptionPane.showMessageDialog(this, "Saved to data.txt");
    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Save failed: " + ex.getMessage());
    }
}
